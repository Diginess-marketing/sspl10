-- Local-dev only: production already has all of these. Recreates the tables and views the
-- admin area and a few public features read, so they work against the local Supabase
-- instead of returning 404s.
--   * Tables that appear in src/integrations/supabase/types.ts use exactly those columns.
--   * The rest (rewards, news_articles, user_profiles, WhatsApp, trial candidates, chat,
--     GA permissions, QR scans) are shaped from how the code reads and writes them.
--   * Views are real views over the local tables, so admin reports show local test data.
--     Their logic approximates production's; the columns match what the pages read.
-- Every table and view is created only when it is missing, so on production this file is
-- a no-op: nothing is created, replaced or granted there. (A plain "create or replace view"
-- would overwrite the real production views, which is why each one is guarded.)
-- Not recreated: the RPC functions (allocate_to_trials, get_workflow_dashboard_stats, ...)
-- and the edge functions (ga4-*, QR generation, emails); those stay unavailable locally.

-- Access rules for a table created by this file (local dev): signed-in users (the admin
-- pages) have full access; anonymous visitors can read and add rows, as public forms do.
create or replace function pg_temp.local_dev_policies(t text) returns void language plpgsql as $f$
begin
  execute format('alter table public.%I enable row level security', t);
  execute format('create policy "local dev signed-in full access" on public.%I for all to authenticated using (true) with check (true)', t);
  execute format('create policy "local dev anon read" on public.%I for select to anon using (true)', t);
  execute format('create policy "local dev anon insert" on public.%I for insert to anon with check (true)', t);
end $f$;

