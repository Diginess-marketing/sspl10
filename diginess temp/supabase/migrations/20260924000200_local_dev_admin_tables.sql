      join public.trials_allocations a on a.workflow_id = w.workflow_id
      left join public.trial_results t on t.allocation_id = a.allocation_id;
  end if;

  ---------------------------------------------------------------------------
  -- Local-only changes to tables production already has (skipped there)
  ---------------------------------------------------------------------------
  if local_dev then
    -- Every user gets a profile, now and on sign-up, so the admin Users page's
    -- user_roles -> user_profiles embed has a row to join and a foreign key to follow.
    insert into public.user_profiles (id, email)
      select id, email from auth.users on conflict (id) do nothing;
    create or replace function public.local_dev_create_profile() returns trigger
      language plpgsql security definer set search_path = public as $f$
    begin
      insert into public.user_profiles (id, email) values (new.id, new.email) on conflict (id) do nothing;
      return new;
    end $f$;
    create trigger local_dev_create_profile after insert on auth.users
      for each row execute function public.local_dev_create_profile();
    alter table public.user_roles
      add constraint user_roles_user_id_profile_fkey foreign key (user_id) references public.user_profiles (id) on delete cascade;

    -- The admin Settings page saves with an upsert; locally admin_settings was read-only.
    create policy "local dev admins write admin_settings" on public.admin_settings for all to authenticated
      using (exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'admin'))
      with check (exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'admin'));
  end if;
end $$;
